#!/usr/bin/env python3
"""
suricata_threshold_baseline.py — evidence for tuning the 14 `detection_filter`
rules that #446 shipped disabled (M23 Stage 3).

Every `count`/`seconds` value on those rules is the starter set's own
illustrative default; none was measured against this deployment's traffic.
A threshold rule cannot be tuned from its own alerts, because while it is
disabled (or its filter is high) it emits none. This tool breaks the loop:

  prepare   Write a BASELINE rules file: the same rules, enabled, with the
            `detection_filter` option removed, so Suricata logs one alert per
            matching packet. NEVER add this file to `rule-files:` in
            configs/suricata/suricata.yaml. Run it as a separate, alert-only
            Suricata run (`suricata -S baseline.rules ...`, or `-r <pcap>`).

  analyze   Read the resulting eve.json file(s) and, for each rule, report the
            highest number of matches any single tracked source/destination
            produced inside the rule's own window, how many keys would have
            reached the CURRENT count, and a suggested count with headroom.

What this does NOT do, and what a human must still decide:
  * It cannot tell whether the baseline period contained an attack. A baseline
    taken during an incident would raise every threshold to hide it. The
    operator vouches that the period was ordinary.
  * "Fires at count" is modelled as: the rule alerts once `count` matches have
    been seen inside `seconds`. Suricata's exact boundary (>= versus >) was not
    verified here; the suggestion adds +1 so it holds under either reading.
  * A suggestion is a starting point for review, never an instruction to edit
    the rule. It never lowers a count below the shipped value (that would raise
    sensitivity with no evidence).
  * Enabling a rule additionally needs a passing true-positive pcap fixture
    (tests/detections/suricata_rules_eval.py promotion gate). None of these 14
    has one yet.

Stdlib only. Usage:
  suricata_threshold_baseline.py prepare --out /tmp/baseline.rules
  suricata_threshold_baseline.py analyze --eve eve.json [--eve more.json] \\
        [--margin 1.25] [--min-days 7] [--format table|json]
"""
from __future__ import annotations

import argparse
import json
import math
import re
import sys
from bisect import bisect_left
from dataclasses import dataclass
from datetime import datetime
from pathlib import Path

DEFAULT_RULES_DIR = Path(__file__).resolve().parents[2] / "rules" / "suricata"

_RULE_RE = re.compile(
    r"^(?P<hash>#\s*)?(?P<action>alert|drop|reject|pass|log)\b.*\(.*\bsid:\s*(?P<sid>\d+)\s*;.*\)\s*$"
)
_FILTER_RE = re.compile(
    r"detection_filter\s*:\s*track\s+(?P<track>by_src|by_dst)\s*,\s*"
    r"count\s+(?P<count>\d+)\s*,\s*seconds\s+(?P<seconds>\d+)\s*;"
)
_MSG_RE = re.compile(r'msg:"(?P<msg>[^"]*)"')


@dataclass(frozen=True)
class Candidate:
    sid: int
    file: str
    msg: str
    track: str      # by_src | by_dst
    count: int
    seconds: int
    text: str       # rule text, enabled (leading '#' stripped), filter intact


def load_candidates(rules_dir: Path) -> list[Candidate]:
    """Every DISABLED rule that carries a detection_filter."""
    out: list[Candidate] = []
    for path in sorted(rules_dir.glob("*.rules")):
        for raw in path.read_text(encoding="utf-8").splitlines():
            m = _RULE_RE.match(raw.strip())
            if not m or m.group("hash") is None:
                continue
            f = _FILTER_RE.search(raw)
            if not f:
                continue
            text = raw.strip().lstrip("#").lstrip()
            msg = _MSG_RE.search(text)
            out.append(Candidate(
                sid=int(m.group("sid")), file=path.name,
                msg=msg.group("msg") if msg else "", track=f.group("track"),
                count=int(f.group("count")), seconds=int(f.group("seconds")),
                text=text,
            ))
    return sorted(out, key=lambda c: c.sid)


def strip_filter(text: str) -> str:
    """Remove the detection_filter option (and nothing else)."""
    # Drop the option and the single space before it; leave every other byte
    # (including runs of spaces inside content:/pcre: strings) untouched.
    out, n = re.subn(r" ?" + _FILTER_RE.pattern, "", text)
    if n != 1:
        raise ValueError(f"expected exactly one detection_filter, found {n}")
    return out


def baseline_rules_text(cands: list[Candidate]) -> str:
    header = (
        "# BASELINE RULES — generated by suricata_threshold_baseline.py (#446).\n"
        "# detection_filter REMOVED: one alert per matching packet. Alert-only,\n"
        "# separate Suricata run. NEVER add this file to rule-files: in\n"
        "# configs/suricata/suricata.yaml.\n"
    )
    return header + "\n".join(strip_filter(c.text) for c in cands) + "\n"


def parse_ts(value: str) -> float:
    """Suricata eve timestamps: 2026-10-24T01:52:12.123456+0000 (offset w/o colon)."""
    for fmt in ("%Y-%m-%dT%H:%M:%S.%f%z", "%Y-%m-%dT%H:%M:%S%z"):
        try:
            return datetime.strptime(value, fmt).timestamp()
        except ValueError:
            continue
    raise ValueError(f"unrecognised timestamp: {value!r}")


def window_max(sorted_ts: list[float], seconds: int) -> int:
    """Largest number of events in any half-open window [t, t+seconds)."""
    best = 0
    j = 0
    for i, t in enumerate(sorted_ts):
        j = max(j, i)
        j = bisect_left(sorted_ts, t + seconds, lo=j)
        best = max(best, j - i)
    return best


@dataclass
class Result:
    cand: Candidate
    events: int
    keys: int
    observed_max: int
    top_key: str
    keys_reaching_current: int
    suggested: int
    note: str


def analyze_events(events, cands: list[Candidate], margin: float):
    """events: iterable of (sid, src_ip, dest_ip, epoch). Returns (results, first, last)."""
    by_sid = {c.sid: c for c in cands}
    series: dict[int, dict[str, list[float]]] = {c.sid: {} for c in cands}
    first = last = None
    for sid, src, dst, ts in events:
        c = by_sid.get(sid)
        if c is None:
            continue
        key = src if c.track == "by_src" else dst
        series[sid].setdefault(key, []).append(ts)
        first = ts if first is None else min(first, ts)
        last = ts if last is None else max(last, ts)

    results: list[Result] = []
    for c in cands:
        per_key = series[c.sid]
        maxes = {k: window_max(sorted(v), c.seconds) for k, v in per_key.items()}
        observed = max(maxes.values(), default=0)
        top = max(maxes, key=lambda k: maxes[k]) if maxes else "-"
        reaching = sum(1 for m in maxes.values() if m >= c.count)
        if observed == 0:
            suggested, note = c.count, "no matching traffic in the baseline: rule is untested, keep shipped value"
        else:
            suggested = max(c.count, math.ceil(observed * margin) + 1)
            note = ("noisy at the shipped count: raise" if suggested > c.count
                    else "shipped count already clears the baseline")
        results.append(Result(c, sum(len(v) for v in per_key.values()), len(per_key),
                              observed, top, reaching, suggested, note))
    return results, first, last


def read_eve(paths: list[Path], stats: dict):
    """Yield (sid, src_ip, dest_ip, epoch) from alert events; stats['skipped'] counts bad lines."""
    stats.setdefault("skipped", 0)
    for p in paths:
        with p.open(encoding="utf-8", errors="replace") as fh:
            for line in fh:
                if '"alert"' not in line:
                    continue
                try:
                    ev = json.loads(line)
                    if ev.get("event_type") != "alert":
                        continue
                    yield (int(ev["alert"]["signature_id"]), ev.get("src_ip", ""),
                           ev.get("dest_ip", ""), parse_ts(ev["timestamp"]))
                except (ValueError, KeyError, TypeError):
                    stats["skipped"] += 1


def render_table(results: list[Result], days: float, min_days: float) -> str:
    lines = []
    if days < min_days:
        lines.append(f"PROVISIONAL: baseline spans {days:.1f} days, less than the {min_days:g} required. "
                     "Do not act on these suggestions.")
    lines.append("sid       rule file                         track   cur(count/s)  events  keys  max/win  >=cur  suggest  note")
    for r in results:
        c = r.cand
        lines.append(f"{c.sid:<9} {c.file:<33} {c.track:<7} {c.count:>4}/{c.seconds:<6}   "
                     f"{r.events:>6} {r.keys:>5} {r.observed_max:>8} {r.keys_reaching_current:>6} {r.suggested:>8}  {r.note}")
    return "\n".join(lines)


def cmd_prepare(args) -> int:
    rules_dir = Path(args.rules_dir).resolve()
    out = Path(args.out).resolve()
    if out == rules_dir or rules_dir in out.parents:
        print(f"[REFUSED] {out} is inside {rules_dir}; a baseline file there could be loaded as real rules.",
              file=sys.stderr)
        return 2
    cands = load_candidates(rules_dir)
    if not cands:
        print("[!] no disabled detection_filter rules found — nothing to baseline.", file=sys.stderr)
        return 1
    out.write_text(baseline_rules_text(cands), encoding="utf-8")
    print(f"[+] wrote {len(cands)} baseline rules to {out}")
    return 0


def cmd_analyze(args) -> int:
    cands = load_candidates(Path(args.rules_dir))
    if args.margin < 1.0:
        print("[REFUSED] --margin below 1.0 would suggest thresholds under the observed noise.", file=sys.stderr)
        return 2
    paths = [Path(p) for p in args.eve]
    missing = [str(p) for p in paths if not p.is_file()]
    if missing:
        print(f"[!] not found: {', '.join(missing)}", file=sys.stderr)
        return 1
    stats: dict = {}
    results, first, last = analyze_events(read_eve(paths, stats), cands, args.margin)
    days = ((last - first) / 86400.0) if first is not None and last is not None else 0.0
    skipped = stats.get("skipped", 0)
    if args.format == "json":
        print(json.dumps({
            "span_days": round(days, 2), "provisional": days < args.min_days, "skipped_lines": skipped,
            "rules": [{"sid": r.cand.sid, "file": r.cand.file, "track": r.cand.track,
                       "current_count": r.cand.count, "seconds": r.cand.seconds, "events": r.events,
                       "keys": r.keys, "observed_max": r.observed_max, "top_key": r.top_key,
                       "keys_reaching_current": r.keys_reaching_current,
                       "suggested_count": r.suggested, "note": r.note} for r in results],
        }, indent=2))
    else:
        print(render_table(results, days, args.min_days))
        if skipped:
            print(f"[!] skipped {skipped} unparseable alert line(s)", file=sys.stderr)
    return 0


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    sub = ap.add_subparsers(dest="cmd", required=True)
    p = sub.add_parser("prepare", help="write the baseline rules file")
    p.add_argument("--rules-dir", default=str(DEFAULT_RULES_DIR))
    p.add_argument("--out", required=True)
    p.set_defaults(fn=cmd_prepare)
    a = sub.add_parser("analyze", help="summarise baseline eve.json alerts")
    a.add_argument("--rules-dir", default=str(DEFAULT_RULES_DIR))
    a.add_argument("--eve", action="append", required=True, help="eve.json path (repeatable)")
    a.add_argument("--margin", type=float, default=1.25)
    a.add_argument("--min-days", type=float, default=7.0)
    a.add_argument("--format", choices=("table", "json"), default="table")
    a.set_defaults(fn=cmd_analyze)
    args = ap.parse_args(argv)
    return args.fn(args)


if __name__ == "__main__":
    sys.exit(main())
